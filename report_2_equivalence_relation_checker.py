"""Report 2 - Equivalence relation checker on A = {1,2,3,4,5}"""

A = [1, 2, 3, 4, 5]
N = len(A)


# ---------- 1. Input ----------
def input_matrix():
    """Read a 5x5 relation matrix row by row and store it as a 2D list."""
    print("Enter the 5x5 relation matrix (one row per line, values 0/1 separated by spaces)")
    matrix = []
    for i in range(N):
        while True:
            try:
                row = list(map(int, input(f"Row {i + 1}: ").split()))
                if len(row) == N and all(v in (0, 1) for v in row):
                    matrix.append(row)
                    break
            except ValueError:
                pass
            print(f"  -> Enter exactly {N} values, each 0 or 1.")
    return matrix


def print_matrix(m, title=""):
    if title:
        print(title)
    for row in m:
        print("  ", " ".join(map(str, row)))


# ---------- 2. Property checks ----------
def is_reflexive(m):
    return all(m[i][i] == 1 for i in range(N))


def is_symmetric(m):
    return all(m[i][j] == m[j][i] for i in range(N) for j in range(N))


def is_transitive(m):
    for i in range(N):
        for j in range(N):
            if m[i][j]:
                for k in range(N):
                    if m[j][k] and not m[i][k]:
                        return False
    return True


def check_equivalence(m):
    r, s, t = is_reflexive(m), is_symmetric(m), is_transitive(m)
    print(f"  Reflexive : {'Yes' if r else 'No'}")
    print(f"  Symmetric : {'Yes' if s else 'No'}")
    print(f"  Transitive: {'Yes' if t else 'No'}")
    if r and s and t:
        print("  => This IS an equivalence relation.")
        return True
    print("  => This is NOT an equivalence relation.")
    return False


# ---------- 3. Equivalence classes ----------
def equivalence_classes(m):
    classes, seen = [], set()
    for i in range(N):
        if i not in seen:
            cls = [j for j in range(N) if m[i][j]]
            seen.update(cls)
            classes.append(cls)
    return classes


def print_classes(m):
    for i in range(N):
        members = [A[j] for j in range(N) if m[i][j]]
        print(f"  [{A[i]}] = {{{', '.join(map(str, members))}}}")
    parts = {tuple(c) for c in equivalence_classes(m)}
    shown = ", ".join("{" + ", ".join(str(A[j]) for j in c) + "}" for c in sorted(parts))
    print(f"  Partition of A: {shown}")


# ---------- 4. Closures ----------
def reflexive_closure(m):
    c = [row[:] for row in m]
    for i in range(N):
        c[i][i] = 1
    return c


def symmetric_closure(m):
    return [[1 if m[i][j] or m[j][i] else 0 for j in range(N)] for i in range(N)]


def transitive_closure(m):  # Warshall's algorithm
    c = [row[:] for row in m]
    for k in range(N):
        for i in range(N):
            for j in range(N):
                if c[i][k] and c[k][j]:
                    c[i][j] = 1
    return c


def apply_closure(m, name, func):
    print(f"\n--- {name} closure ---")
    print_matrix(m, "Before:")
    new = func(m)
    print_matrix(new, "After:")
    print("Re-check after closure:")
    if check_equivalence(new):
        print_classes(new)
    return new


# ---------- step-by-step helper (so each stage can be captured) ----------
def pause(message):
    input(f"\n>>> {message}  [Press Enter to continue]")


# ---------- main ----------
def main():
    m = input_matrix()
    print_matrix(m, "\nInput relation matrix:")
    pause("Condition 1 done: matrix stored")

    print("\n=== Property check ===")
    if check_equivalence(m):
        pause("Condition 2 done: it is an equivalence relation")
        print("\n=== Equivalence classes ===")
        print_classes(m)
        pause("Condition 3 done: classes printed")
        return
    pause("Condition 2 done: it is NOT an equivalence relation")

    # 4. Closures for each missing property
    print("\n=== Closures for missing properties ===")
    if not is_reflexive(m):
        apply_closure(m, "Reflexive", reflexive_closure)
        pause("Reflexive closure done")
    if not is_symmetric(m):
        apply_closure(m, "Symmetric", symmetric_closure)
        pause("Symmetric closure done")
    if not is_transitive(m):
        apply_closure(m, "Transitive", transitive_closure)
        pause("Transitive closure done")

    # Extra feature: combine all closures -> always an equivalence relation
    print("\n=== [Extra] Smallest equivalence relation containing the input ===")
    full = transitive_closure(symmetric_closure(reflexive_closure(m)))
    print_matrix(full, "Reflexive -> Symmetric -> Transitive closure:")
    if check_equivalence(full):
        print_classes(full)
    pause("Extra feature done")


if __name__ == "__main__":
    main()